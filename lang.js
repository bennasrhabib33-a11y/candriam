const LANG_META = {
  fr: { label: "Français", flag: "🇫🇷", dir: "ltr", code: "fr" },
  en: { label: "English", flag: "🇬🇧", dir: "ltr", code: "en" },
  es: { label: "Español", flag: "🇪🇸", dir: "ltr", code: "es" },
  de: { label: "Deutsch", flag: "🇩🇪", dir: "ltr", code: "de" },
};

function getLang() {
  return localStorage.getItem("fai_lang") || "fr";
}

function setLang(code) {
  localStorage.setItem("fai_lang", code);
  if (typeof i18nApply === "function") i18nApply(code); // garde i18n.js synchronisé
  applyLang(code);
  updateSwitcher(code);
}

function applyLang(code) {
  const t = TRANSLATIONS[code] || TRANSLATIONS.fr;
  document.documentElement.lang = code;

  // Appliquer toutes les clés data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Attributs HTML (placeholder, aria-label, alt)
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.dataset.i18nAria;
    if (t[key] !== undefined) el.setAttribute("aria-label", t[key]);
  });

  // Options <select> du simulateur (type de prêt)
  const opts = document.querySelectorAll("#sim-type option");
  if (opts.length === 4) {
    opts[0].textContent = t.sim_type1 || opts[0].textContent;
    opts[1].textContent = t.sim_type2 || opts[1].textContent;
    opts[2].textContent = t.sim_type3 || opts[2].textContent;
    opts[3].textContent = t.sim_type4 || opts[3].textContent;
  }
}

function updateSwitcher(code) {
  const meta = LANG_META[code];
  if (!meta) return;
  document.querySelectorAll(".lang-current-flag").forEach(el => el.textContent = meta.flag);
  document.querySelectorAll(".lang-current-label").forEach(el => el.textContent = meta.label);
  document.querySelectorAll(".lang-option").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === code);
  });
}

// Injecter automatiquement le switcher dans le header
function injectSwitcher() {
  const cta = document.querySelector(".nav-cta");
  if (!cta || document.getElementById("lang-switcher")) return;

  const lang = getLang();
  const meta = LANG_META[lang];

  const sw = document.createElement("div");
  sw.id = "lang-switcher";
  sw.innerHTML = `
    <button class="lang-toggle" onclick="document.getElementById('lang-dropdown').classList.toggle('open')">
      <span class="lang-current-flag">${meta.flag}</span>
      <span class="lang-current-label">${meta.label}</span>
      <svg width="10" height="6" viewBox="0 0 10 6" fill="none"><path d="M1 1l4 4 4-4" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>
    </button>
    <div class="lang-dropdown" id="lang-dropdown">
      ${Object.entries(LANG_META).map(([code, m]) => `
        <button class="lang-option ${code === lang ? 'active' : ''}" data-lang="${code}" onclick="setLang('${code}');document.getElementById('lang-dropdown').classList.remove('open')">
          <span>${m.flag}</span> ${m.label}
        </button>
      `).join("")}
    </div>
  `;

  cta.insertBefore(sw, cta.firstChild);

  // Fermer en cliquant ailleurs
  document.addEventListener("click", (e) => {
    if (!sw.contains(e.target)) document.getElementById("lang-dropdown")?.classList.remove("open");
  });
}

